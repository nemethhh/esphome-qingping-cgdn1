#!/usr/bin/env python3
"""Extract the stock CGDN1 sensor label icons into a C header for the ESPHome display driver.

The stock 4.8.5 app (CGDN1_ESP_4.8.5_*.bin) draws every label as a
1-bpp bitmap through oled_gui_draw_image: `W` bytes per
page-row, byte = 8 GUI-Y pixels, LSB first, pixel(X + col, Y + page*8 + bit). This tool reads
those bytes straight from the app image and writes them UPRIGHT (as the glass shows them) as
row-major, MSB-first bitmaps, so the driver can draw them on its rotated logical canvas.

Upright orientation: verified on the stock digits ("4", "7" only read correctly this way) --
upright(row, col) = GUI(X = W - 1 - row, Y = col); upright width = H (the page axis), height = W.

  gen_stock_icons.py STOCK_APP.bin [--out .../stock_icons.h] [--ascii]

Local only: reads a file, writes a file.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "components/cgdn1_display/stock_icons.h"

# name, DROM address, W (bytes per page-row = upright height), H (page axis = upright width), what.
# Addresses/sizes from the stock 4.8.5 GUI code (unit/label icons, FUN_400e58bc).
ICONS = [
    ("CO2", 0x3F405279, 15, 40, 'label "CO2"'),
    ("PM25", 0x3F405210, 15, 56, 'label "pm2.5"'),
    ("PM10", 0x3F4051A7, 15, 56, 'label "pm10"'),
    ("THERMOMETER", 0x3F405198, 15, 8, "thermometer (temperature)"),
    ("DROPLET", 0x3F40517A, 15, 16, "droplet (humidity)"),
    # Page bitmaps (stock page/slide renderer).
    ("HUGE_0", 0x3F405EBB, 56, 32, 'HUGE outline digit "0"'),
    ("HUGE_1", 0x3F405E4B, 56, 16, 'HUGE outline digit "1"'),
    ("HUGE_2", 0x3F405D6B, 56, 32, 'HUGE outline digit "2"'),
    ("HUGE_3", 0x3F405C8B, 56, 32, 'HUGE outline digit "3"'),
    ("HUGE_4", 0x3F405BAB, 56, 32, 'HUGE outline digit "4"'),
    ("HUGE_5", 0x3F405ACB, 56, 32, 'HUGE outline digit "5"'),
    ("HUGE_6", 0x3F4059EB, 56, 32, 'HUGE outline digit "6"'),
    ("HUGE_7", 0x3F40590B, 56, 32, 'HUGE outline digit "7"'),
    ("HUGE_8", 0x3F40582B, 56, 32, 'HUGE outline digit "8"'),
    ("HUGE_9", 0x3F40574B, 56, 32, 'HUGE outline digit "9"'),
    ("HUGE_DOT", 0x3F4052C4, 8, 8, "HUGE decimal point"),
    ("PERCENT", 0x3F40515C, 15, 16, 'unit "%"'),
    ("E2", 0x3F404DBB, 55, 72, 'error page "E2"'),
    ("LOADER_0", 0x3F4060E5, 11, 40, "loader animation frame 0"),
    ("LOADER_1", 0x3F4060AE, 11, 40, "loader animation frame 1"),
    ("LOADER_2", 0x3F406077, 11, 40, "loader animation frame 2"),
    ("PAGE_1", 0x3F404247, 4, 32, "page indicator, 1st dot active"),
    ("PAGE_2", 0x3F404237, 4, 32, "page indicator, 2nd dot active"),
    ("PAGE_3", 0x3F404227, 4, 32, "page indicator, 3rd dot active"),
    ("PAGE_4", 0x3F404217, 4, 32, "page indicator, 4th dot active"),
    ("PAGE_5", 0x3F404207, 4, 32, "page indicator, 5th dot active"),
]

# Index tables emitted after the icons: C array name, member icon names (in index order).
GROUPS = [
    ("HUGE_DIGITS", [f"HUGE_{i}" for i in range(10)]),
    ("LOADER_FRAMES", [f"LOADER_{i}" for i in range(3)]),
    ("PAGE_DOTS", [f"PAGE_{i}" for i in range(1, 6)]),
]


def load_segments(image: bytes) -> list[tuple[int, int, int]]:
    """ESP32 app image -> [(load address, length, file offset)]."""
    if len(image) < 24 or image[0] != 0xE9:
        raise ValueError("not an ESP32 app image (magic 0xE9)")
    segs, off = [], 24
    for _ in range(image[1]):
        addr, length = struct.unpack_from("<II", image, off)
        segs.append((addr, length, off + 8))
        off += 8 + length
    return segs


def read(image: bytes, segs, addr: int, n: int) -> bytes:
    for base, length, off in segs:
        if base <= addr and addr + n <= base + length:
            return image[off + addr - base: off + addr - base + n]
    raise ValueError(f"{addr:#x}+{n} not in any segment")


def upright(raw: bytes, w: int, h: int) -> list[list[int]]:
    """Stock page-row bitmap (w bytes per page, h px along the page axis) -> rows of the
    upright picture (h wide, w tall)."""
    def gui(x, y):
        return (raw[(y // 8) * w + x] >> (y & 7)) & 1
    return [[gui(w - 1 - row, col) for col in range(h)] for row in range(w)]


def pack(rows: list[list[int]]) -> bytes:
    """Row-major, MSB = leftmost, each row padded to whole bytes."""
    out = bytearray()
    for r in rows:
        for i in range(0, len(r), 8):
            b = 0
            for j, v in enumerate(r[i:i + 8]):
                b |= v << (7 - j)
            out.append(b)
    return bytes(out)


def header(icons: list[tuple[str, str, list[list[int]]]], source: str) -> str:
    lines = [
        "#pragma once",
        "// GENERATED by tools/gen_stock_icons.py -- do not edit.",
        f"// Stock GUI bitmaps (sensor labels, HUGE digits, page glyphs) from the stock CGDN1 4.8.5 app image ({source});",
        "// drawn upright, row-major, MSB = leftmost pixel, rows padded to bytes.",
        "#include <cstdint>",
        "",
        "namespace esphome::cgdn1_display {",
        "",
        "struct StockIcon {",
        "  uint8_t width;",
        "  uint8_t height;",
        "  const uint8_t *data;",
        "};",
        "",
    ]
    for name, what, rows in icons:
        w, h = len(rows[0]), len(rows)
        data = pack(rows)
        lines.append(f"// {what}, {w}x{h}")
        for r in rows:
            lines.append("//   " + "".join("#" if v else "." for v in r))
        body = ", ".join(f"0x{b:02X}" for b in data)
        lines.append(f"inline constexpr uint8_t ICON_{name}_DATA[] = {{{body}}};")
        lines.append(f"inline constexpr StockIcon ICON_{name} = {{{w}, {h}, ICON_{name}_DATA}};")
        lines.append("")
    for name, members in GROUPS:
        refs = ", ".join(f"&ICON_{m}" for m in members)
        lines.append(f"inline constexpr const StockIcon *{name}[{len(members)}] = {{{refs}}};")
    lines.append("")
    lines += ["}  // namespace esphome::cgdn1_display", ""]
    return "\n".join(lines)


def extract(image: bytes) -> list[tuple[str, str, list[list[int]]]]:
    segs = load_segments(image)
    out = []
    for name, addr, w, h, what in ICONS:
        raw = read(image, segs, addr, w * ((h + 7) // 8))
        out.append((name, what, upright(raw, w, h)))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image", help="stock app image, e.g. CGDN1_ESP_4.8.5_*.bin")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--ascii", action="store_true", help="print the icons, write nothing")
    a = ap.parse_args(argv)
    icons = extract(Path(a.image).read_bytes())
    if a.ascii:
        for name, what, rows in icons:
            print(f"{name} ({what})")
            print("\n".join("".join("#" if v else "." for v in r) for r in rows))
        return 0
    Path(a.out).write_text(header(icons, Path(a.image).name))
    print(f"wrote {a.out} ({len(icons)} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
